import { useMemo } from "react";
import { downloadReportUrl, downloadZipUrl } from "../lib/api";
import { useAppStore } from "../lib/store";

const formatDateTime = (value: string) => {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return { date: "-", time: "-", stamp: "-" };
  }
  return {
    date: date.toLocaleDateString(),
    time: date.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit", second: "2-digit" }),
    stamp: date.toISOString(),
  };
};

export default function HistoryPage() {
  const store = useAppStore();
  const history = useMemo(() => store.history, [store.history]);

  return (
    <div className="page">
      <div className="page-grid wide single">
        <section className="card panel">
          <div className="panel-header">
            <h1 className="page-title">History</h1>
            <p className="page-subtitle">Recent ABL ZIP packages generated by the platform.</p>
          </div>

          {history.length === 0 ? (
            <div className="card soft" style={{ marginBottom: 10 }}>
              <div className="card-title">No history yet</div>
              <p className="muted">Run a conversion to see generated ZIP files and timestamps here.</p>
            </div>
          ) : (
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th>File</th>
                    <th>Generated</th>
                    <th>Job</th>
                    <th>Actions</th>
                  </tr>
                </thead>
                <tbody>
                  {history.map((item) => {
                    const formatted = formatDateTime(item.createdAt);
                    const zipUrl = downloadZipUrl(item.jobId);
                    const reportUrl = downloadReportUrl(item.jobId);
                    return (
                      <tr key={item.id}>
                        <td>
                          <div style={{ fontWeight: 700 }}>{item.fileName}</div>
                          <div className="muted">ZIP package</div>
                        </td>
                        <td>
                          <div>{formatted.date} {formatted.time}</div>
                          <div className="muted">{formatted.stamp}</div>
                        </td>
                        <td>{item.jobId}</td>
                        <td>
                          <div className="row" style={{ justifyContent: "flex-start" }}>
                            <a className="btn tertiary" href={zipUrl} download={item.fileName}>Download ZIP</a>
                            <a className="btn tertiary" href={reportUrl} target="_blank" rel="noreferrer">Report</a>
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
        </section>
      </div>
    </div>
  );
}
